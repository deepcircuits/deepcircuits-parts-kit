// Builds the kit from src/: writes src/tokens.js and tokens.css from project/tokens.json, the type declarations of each
// entry point, and the classic bundle project/generators/bundle.js (window.PartsKit) that the gallery and the checks load.
// esbuild bundles every entry point's exports onto one object, in an immediately invoked function.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import { tokensCss } from './tokens-css.mjs';

const tokens = JSON.parse(readFileSync('project/tokens.json', 'utf8'));
const fallback = {};
const colors = [];
for (const family of ['color', 'spacing', 'radius', 'stroke', 'opacity'])
  for (const t of tokens[family].tokens) {
    fallback[t.name] = typeof t.value === 'string' ? t.value : t.value.light;
    if (family === 'color') colors.push(t.name);
  }
writeFileSync(
  'src/tokens.js',
  "// Generated by build.mjs from project/tokens.json: every token's light value, which the generators fall back to, and the colour token names. Do not edit.\n" +
    `export const FALLBACK = ${JSON.stringify(fallback)};\n` +
    `export const COLOR_TOKENS = ${JSON.stringify(colors)};\n`,
);
writeFileSync('tokens.css', tokensCss(tokens));

// The entry points the package exports (package.json "exports"), each with generated declarations naming its exports'
// types on PartsKit. A deprecated root name is typed as the name that replaces it and marked @deprecated.
const ENTRIES = [
  'index',
  'templates',
  'primitives',
  'check',
  'mount',
  'dom',
  'element',
  'controls',
  'catalog',
  ...readdirSync('src/families')
    .filter(f => f.endsWith('.js'))
    .map(f => `families/${f.slice(0, -3)}`),
];
const { DEPRECATED } = await import(pathToFileURL('src/deprecated.js').href);
const movedTo = ({ use, from }) =>
  from ? `Import ${use} from '@deepcircuits/parts-kit/${from}'.` : `Use ${use}, which draws the same part.`;
const exportsOf = {};
for (const name of ENTRIES)
  exportsOf[name] = Object.keys(await import(pathToFileURL(`src/${name}.js`).href)).filter(n => n !== 'default');
for (const name of ENTRIES) {
  const up = '../'.repeat(name.split('/').length);
  writeFileSync(
    `src/${name}.d.ts`,
    [
      `// Generated by build.mjs: the exports of src/${name}.js, typed in project/generators/index.d.ts. Do not edit.`,
      `import type { PartsKit } from '${up}project/generators/index.d.ts';`,
      ...(name === 'index' ? [`export type * from '${up}project/generators/index.d.ts';`] : []),
      ...exportsOf[name].map(n =>
        name === 'index' && DEPRECATED[n]
          ? `/** @deprecated ${movedTo(DEPRECATED[n])} */\nexport declare const ${n}: PartsKit['${DEPRECATED[n].use}'];`
          : `export declare const ${n}: PartsKit['${n}'];`,
      ),
      // Importing the element entry defines <parts-kit-part>, so its type is known by tag name.
      ...(name === 'element'
        ? [
            `import type { PartElement } from '${up}project/generators/index.d.ts';`,
            'declare global {',
            '  interface HTMLElementTagNameMap {',
            "    'parts-kit-part': PartElement;",
            '  }',
            '}',
          ]
        : []),
      '',
    ].join('\n'),
  );
}

// The catalog's types, from src/options.js: every part id, the options each one takes, and drawPart typed by them.
const { CATALOG, RENAMED_IDS } = await import(pathToFileURL('src/catalog.js').href);
const { OPTIONS } = await import(pathToFileURL('src/options.js').href);
const literal = v => JSON.stringify(v);
function typeOf(spec) {
  switch (spec.type) {
    case 'boolean':
      return 'boolean';
    case 'number':
    case 'integer':
      return 'number';
    case 'level':
      return 'Lit';
    case 'enum':
      return spec.choices.map(c => literal(c.value)).join(' | ');
    case 'color':
      return 'LensColor';
    case 'pixel':
      return 'PixelColor';
    case 'text':
      return spec.numeric ? 'string | number' : 'string';
    case 'frame':
      return 'ScreenPixels';
    case 'point':
      return '{ x: number; y: number }';
    case 'list': {
      const item = typeOf(spec.items);
      return `readonly (${item})[]`;
    }
    case 'object':
      return `{ ${Object.entries(spec.fields)
        .map(([k, f]) => `${doc(f)}${k}?: ${typeOf(f)}`)
        .join('; ')} }`;
    default:
      throw new Error(`no type for ${spec.type}`);
  }
}
function doc(spec) {
  const bits = [spec.label && `${spec.label}.`];
  if (spec.min !== undefined && spec.max !== undefined)
    bits.push(`${spec.min} to ${spec.max}${spec.unit ? ` ${spec.unit}` : ''}.`);
  if (spec.default !== undefined && spec.type !== 'frame') bits.push(`Default ${literal(spec.default)}.`);
  if (spec.deprecated) bits.push(`@deprecated Use ${spec.deprecated}.`);
  const text = bits.filter(Boolean).join(' ').replace(/\*\//g, '* /');
  return text ? `/** ${text} */ ` : '';
}
const optionsType = e => {
  const all = { ...e.options };
  for (const [k, spec] of Object.entries(OPTIONS[e.fn])) if (spec.deprecated && !(k in e.preset)) all[k] = spec;
  const body = Object.entries(all).map(([k, spec]) => `    ${doc(spec)}${k}?: ${typeOf(spec)};`);
  return body.length ? `{\n${body.join('\n')}\n  }` : 'Record<string, never>';
};
writeFileSync(
  'project/generators/catalog.d.ts',
  [
    '// Generated by build.mjs from src/catalog.js and src/options.js: the options each catalog part takes. Do not edit.',
    "import type { Artwork, LensColor, Lit, PixelColor, ScreenPixels } from './index.d.ts';",
    '',
    '/** The options of each catalog part, by id. */',
    'export interface PartOptionsById {',
    ...CATALOG.map(
      e =>
        `  /** ${e.name}: ${e.fn}${Object.keys(e.preset).length ? ` ${literal(e.preset)}` : ''}. */\n  ${literal(e.id)}: ${optionsType(e)};`,
    ),
    '}',
    '/** A catalog part id. */',
    'export type PartId = keyof PartOptionsById;',
    '/** The ids the catalog has renamed, each with the id it draws now. */',
    'export interface RenamedPartIds {',
    ...Object.entries(RENAMED_IDS).map(([from, to]) => `  ${literal(from)}: ${literal(to)};`),
    '}',
    '/** An id the catalog has renamed; it still draws its part. */',
    'export type RenamedPartId = keyof RenamedPartIds;',
    '/** The options of part `Id`, by its id or an id it was renamed from. */',
    'export type PartOptions<Id extends PartId | RenamedPartId> = Id extends PartId',
    '  ? PartOptionsById[Id]',
    '  : Id extends RenamedPartId',
    '    ? PartOptionsById[RenamedPartIds[Id]]',
    '    : never;',
    '/** A catalog part drawn: its id and its options together, for a list of parts to draw. */',
    'export type PartCall = { [Id in PartId]: { id: Id; options?: PartOptionsById[Id] } }[PartId];',
    // The renamed ids first: a call that fits neither is reported against the last overload, the current ids.
    'export interface DrawPart {',
    '  /** @deprecated A renamed id: use the id it maps to in RENAMED_IDS. */',
    '  <Id extends RenamedPartId>(id: Id, options?: PartOptionsById[RenamedPartIds[Id]]): Artwork;',
    '  /** Draws catalog part `id` with `options`, the ones its entry lists. Throws for an unknown id, an unknown option (naming the nearest) or a value of the wrong type. */',
    '  <Id extends PartId>(id: Id, options?: PartOptionsById[Id]): Artwork;',
    '}',
    '',
  ].join('\n'),
);

// The bundle: every entry point's names on one object.
const names = [...new Set(Object.values(exportsOf).flat())];
const banner = `/*
 * DeepCircuits Parts Kit: original part artwork generators. Built from src/ by build.mjs with esbuild; edit the modules there.
 *
 * Every generator returns an Artwork: { width, height, svg, pins }. Pixels are CSS pixels at 96 dpi, so 0.1 inch
 * is 9.6 px (PITCH) and every pin sits on that pitch relative to the part's first pin. The SVG uses presentation
 * attributes only (no <style>, no style attributes), because sanitizers strip both. A part's body keeps its fixed
 * material palette; anything that faces the canvas (pin names, symbols) is currentColor. Colours come from the
 * design tokens: see setTokenMode.
 */`;
const result = await build({
  stdin: {
    contents: ENTRIES.map(name => `export * from './src/${name}.js';`).join('\n'),
    resolveDir: '.',
    sourcefile: 'bundle-entry.js',
  },
  bundle: true,
  format: 'iife',
  globalName: 'PartsKit',
  target: 'es2018',
  charset: 'utf8',
  write: false,
  banner: { js: banner },
  // A plain object on the global, so a page or a check can replace a function on it (the checks stub mount).
  footer: { js: 'globalThis.PartsKit = Object.assign({}, PartsKit);' },
});
const out = result.outputFiles[0].text;
if (/<\/script|<!--/i.test(out)) throw new Error('bundle contains a literal </script or <!--');
writeFileSync('project/generators/bundle.js', out);
console.log('bundle.js', out.length, 'bytes,', ENTRIES.length, 'entry points,', names.length, 'names');
